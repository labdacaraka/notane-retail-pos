const START_B = 104
const STOP_CODE = 106

/**
 * Menghasilkan string jalur bar Code128 (daftar rectangle SVG)
 */
export function generateCode128Svg(text: string, height: number = 36): string {
  if (!text || text.trim() === '') return ''
  const clean = text.trim()

  const codes: number[] = [START_B]
  let checksum = START_B

  for (let i = 0; i < clean.length; i++) {
    const charCode = clean.charCodeAt(i)
    // Code 128B map: ASCII 32 - 127 -> Code 0 - 95
    const value = charCode >= 32 && charCode <= 126 ? charCode - 32 : 0
    codes.push(value)
    checksum += value * (i + 1)
  }

  const checkDigit = checksum % 103
  codes.push(checkDigit)
  codes.push(STOP_CODE)

  // Buat modul-modul bar hitam
  let currentX = 10 // Quiet zone kiri 10px
  const rects: string[] = []

  for (let i = 0; i < codes.length; i++) {
    const code = codes[i]
    const pattern = CODE128_PATTERNS[code]
    if (!pattern) continue

    for (let p = 0; p < pattern.length; p++) {
      const width = pattern[p]
      if (p % 2 === 0) {
        // Bar hitam
        rects.push(`<rect x="${currentX}" y="0" width="${width}" height="${height}" fill="#000000" />`)
      }
      currentX += width
    }

    // Karakter Stop (106) memiliki bar penutup tambahan lebar 2 di akhir
    if (code === STOP_CODE) {
      rects.push(`<rect x="${currentX}" y="0" width="2" height="${height}" fill="#000000" />`)
      currentX += 2
    }
  }

  currentX += 10 // Quiet zone kanan

  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${currentX} ${height}" preserveAspectRatio="none" style="width: 100%; height: 100%; display: block;">${rects.join('')}</svg>`
}
